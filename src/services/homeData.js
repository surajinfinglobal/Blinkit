export function normalizeProduct(item, category, i) {
  const priceText = item.price || '₹ 100 Per/ kg';

  const price = Number(
    priceText.replace(/[^\d.]/g, '')
  );

  return {
    id: `${category}-${item.id ?? i + 1}`,
    name: item.name || item.alt || `Product ${i + 1}`,
    price,
    priceLabel: priceText,
    image: item.image,
    rating: item.rating || 4,
    category,
    unit: priceText.split('Per/')[1]?.trim() || 'kg',
  };
}
